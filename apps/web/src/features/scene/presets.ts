export type ScenePresetId = (typeof PRESET_IDS)[number];

/** A catalog value, optionally with its strength within the preset (default 1). */
export type PresetChoice = string | readonly [value: string, strength: number];

export interface ScenePreset {
  readonly id: ScenePresetId;
  readonly label: string;
  /** One line for prompts and debug panels. */
  readonly summary: string;
  readonly settings: Readonly<Record<SceneKey, PresetChoice>>;
  /** Candidate layout IDs from scene-assets layouts.v1.json; only `vibe_selected` layouts are eligible. */
  readonly setPieces?: readonly string[];
}

