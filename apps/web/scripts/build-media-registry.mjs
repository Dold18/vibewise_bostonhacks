#!/usr/bin/env node
/** Converts verification reports into the typed media registry.
 * Usage: node scripts/build-media-registry.mjs --tracks <youtube-tracks.json> --images <commons-images.json> [--evokes <evokes.json>]
 * Only rows that passed verification are emitted; failures abort the build. */
import { readFileSync, writeFileSync } from 'node:fs';

const arg = (name) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : undefined; };
const out = new URL('../src/features/vibe/media/data/', import.meta.url);
const header = (what, how) => `// GENERATED by scripts/build-media-registry.mjs — do not edit by hand.\n// ${what}\n// Verification: ${how}\n`;
const fail = (m) => { console.error(m); process.exit(1); };

if (arg('tracks')) {
  const rows = JSON.parse(readFileSync(arg('tracks'), 'utf8'));
  const tracks = rows.map((r) => {
    if (r.oembed_status !== 200 || r.playable_in_embed !== true || r.playability_status !== 'OK' || r.age_restricted !== false) fail(`Unverified track ${r.id}`);
    if (!/^[A-Za-z0-9_-]{11}$/.test(r.video_id)) fail(`Bad video id ${r.id}`);
    return { id: r.id, kind: 'youtube', videoId: r.video_id, song: r.song, artist: r.artist, year: r.year, mood: r.mood, sound: r.sound, channel: r.channel_name, channelUrl: r.channel_url, officialBasis: r.official_basis, verifiedAt: r.verified_at, verification: 'YouTube oEmbed 200 + watch page playableInEmbed:true, playabilityStatus OK, not age-restricted, official channel' };
  });
  writeFileSync(new URL('tracks.ts', out), `${header('Official YouTube uploads, played only in YouTube\'s visible, unmodified player.', 'oEmbed + watch-page playability, checked 2026-11-21 from one US network location; region availability may differ.')}import type { TrackAsset } from '../types.ts';\nexport const YOUTUBE_TRACKS: readonly TrackAsset[] = ${JSON.stringify(tracks, null, 1)};\n`);
  console.log(`tracks: ${tracks.length}`);
}

if (arg('images')) {
  const rows = JSON.parse(readFileSync(arg('images'), 'utf8'));
  const evokes = arg('evokes') ? JSON.parse(readFileSync(arg('evokes'), 'utf8')) : {};
  const ok = /^(cc0|public domain|pd|cc[ -]by(-sa)?[ -]\d\.\d)/i;
  // Excluded for rights caution even though the file license verified: a still whose character
  // remains a live trademark, and a photo dominated by a third-party copyrighted artwork.
  const exclude = new Set((arg('exclude') ?? '').split(',').filter(Boolean));
  const images = rows.filter((r) => !exclude.has(r.id)).map((r) => {
    if (!ok.test(r.license_short)) fail(`Unaccepted license ${r.id}: ${r.license_short}`);
    if (!/^https:\/\/(upload|thumb)\.wikimedia\.org\//.test(r.thumb_url)) fail(`Bad URL ${r.id}`);
    const src = r.thumb_url.split('?')[0];
    const sa = /sa/i.test(r.license_short);
    const kind = r.is_public_domain_film_still ? 'public_domain_film_still' : /^17|nasa|space/i.test(r.category) ? 'space_photo' : 'photo';
    return {
      id: r.id, kind, src, width: r.thumb_width, height: r.thumb_height, subject: r.subject,
      alt: r.subject, tags: r.mood_tags, evokes: evokes[r.id] ?? r.subject, ...(r.film_title_year ? { film: r.film_title_year } : {}),
      rights: { source: 'wikimedia_commons', license: r.license_short, ...(r.license_url ? { licenseUrl: r.license_url } : {}), author: (r.author || 'Unknown').slice(0, 120), sourceUrl: r.description_url, verifiedAt: r.verified_at, verification: r.verification, adaptation: !sa },
    };
  });
  writeFileSync(new URL('images.ts', out), `${header('Wikimedia Commons files with machine-verified licenses (extmetadata). Credit is shown with every image.', 'Commons API LicenseShortName/Artist + thumbnail HEAD 200, 2026-11-21. CC BY-SA files are displayed unmodified only (adaptation:false).')}import type { ImageAsset } from '../types.ts';\nexport const COMMONS_IMAGES: readonly ImageAsset[] = ${JSON.stringify(images, null, 1)};\n`);
  console.log(`images: ${images.length}`);
}
