-- 5.3 Keep registry and type rows in step.
-- Delete: a direct type-row delete also removes the registry row (and, by cascade, the
-- shared rows). When the delete came from the registry, the row is already gone: no-op.
create function public.places_sync_delete()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  delete from public.places where id = old.id;
  return null;
end;
$$;

-- place_id change (ingest's rekey "promote"): copy the new wire id to the registry.
create function public.places_sync_place_id()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  update public.places set place_id = new.place_id where id = new.id;
  return null;
end;
$$;

create trigger places_sync_delete
  after delete on public.restaurants
  for each row execute function public.places_sync_delete();
create trigger places_sync_place_id
  after update of place_id on public.restaurants
  for each row execute function public.places_sync_place_id();

-- 5.4 Type tables: the type-neutral columns of restaurants plus `kind`. No food columns.
