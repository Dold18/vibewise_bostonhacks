-- 5.5 Views. place_points replaces restaurant_points.
drop view public.restaurant_points;

-- Plain coordinates for the pipeline (PostgREST returns geography as hex EWKB). Pipeline only.
create view public.place_points
with (security_invoker = true) as
select 'restaurants'::text as place_type, id, place_id, name,
       extensions.st_y(location::extensions.geometry) as lat,
       extensions.st_x(location::extensions.geometry) as lng,
       website, address, osm_tags, media_checked_at, deals_checked_at, last_seen_at
from public.restaurants
union all
select 'museums'::text, id, place_id, name,
       extensions.st_y(location::extensions.geometry),
       extensions.st_x(location::extensions.geometry),
       website, address, osm_tags, media_checked_at, deals_checked_at, last_seen_at
from public.museums
union all
select 'parks'::text, id, place_id, name,
       extensions.st_y(location::extensions.geometry),
       extensions.st_x(location::extensions.geometry),
       website, address, osm_tags, media_checked_at, deals_checked_at, last_seen_at
from public.parks
union all
select 'landmarks'::text, id, place_id, name,
       extensions.st_y(location::extensions.geometry),
       extensions.st_x(location::extensions.geometry),
       website, address, osm_tags, media_checked_at, deals_checked_at, last_seen_at
from public.landmarks
union all
select 'entertainment'::text, id, place_id, name,
       extensions.st_y(location::extensions.geometry),
       extensions.st_x(location::extensions.geometry),
       website, address, osm_tags, media_checked_at, deals_checked_at, last_seen_at
from public.entertainment;

-- Public catalog for vibe search and the map index. security_invoker: the type tables' RLS applies.
create view public.catalog_places
with (security_invoker = true) as
select id, place_id, 'restaurants'::text as place_type, source, source_id, name, location,
       category as kind, description, embedding
from public.restaurants
union all
select id, place_id, 'museums'::text, source, source_id, name, location, kind, description, embedding
from public.museums
union all
select id, place_id, 'parks'::text, source, source_id, name, location, kind, description, embedding
from public.parks
union all
select id, place_id, 'landmarks'::text, source, source_id, name, location, kind, description, embedding
from public.landmarks
union all
select id, place_id, 'entertainment'::text, source, source_id, name, location, kind, description, embedding
from public.entertainment;

revoke all on public.place_points from anon, authenticated;
grant select on public.place_points to service_role;

revoke all on public.catalog_places from anon, authenticated;
grant select on public.catalog_places, public.places to anon, authenticated;
