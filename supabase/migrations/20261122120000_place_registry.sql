  id                bigint primary key references public.places (id) on delete cascade,
  place_id          text not null unique,
  source            text not null check (source in ('osm', 'foursquare')),
  source_id         text not null,
  fsq_place_id      text unique,
  name              text not null,
  location          extensions.geography(Point, 4326) not null,
  address           text,
  website           text,
  phone             text,
  kind              text not null,            -- e.g. museum, gallery
  hours             jsonb,                    -- null means unknown, never "closed"
