-- Place registry: one id space for every place type, so the shared tables
-- (student_reviews, place_photos, place_vibe_inputs, place_deals) can hold rows for
-- museums, parks, landmarks and entertainment as well as restaurants.
-- Spec: docs/superpowers/specs/2026-11-21-non-food-places-design.md §5
--
-- Forward migration on populated data: restaurants keep their ids, so every existing
-- photo, stored copy (pipeline/<id>/… paths), vibe input and deal stays attached.

-- 5.1 Registry.
create table public.places (
  id          bigint generated by default as identity primary key,
  place_id    text not null unique,          -- wire id, same value as the type row's place_id
  place_type  text not null check (place_type in ('restaurants', 'museums', 'parks', 'landmarks', 'entertainment')),
  created_at  timestamptz not null default now()
);

-- 5.2 Move restaurants onto the registry with the same ids.
insert into public.places (id, place_id, place_type)
select id, place_id, 'restaurants' from public.restaurants;

select setval(pg_get_serial_sequence('public.places', 'id'),
              (select coalesce(max(id), 0) from public.places) + 1, false);

-- A type row's id is its registry id (shared primary key). The pipeline creates the
-- registry row first and inserts the type row with that id.
alter table public.restaurants alter column id drop identity;
alter table public.restaurants
  add constraint restaurants_id_fkey foreign key (id) references public.places (id) on delete cascade;

