-- Deal markers: student discounts and specials per place (DECISIONS.md P-015).
-- Spec: docs/superpowers/specs/2026-11-21-deal-markers-design.md §1, §2
-- Pipeline rows are written with the secret key; there are no client writes.

create table public.place_deals (
  id             bigint generated by default as identity primary key,
  restaurant_id  bigint not null references public.restaurants (id) on delete cascade,
  kind           text not null check (kind in ('student', 'special')),
  title          text not null check (char_length(title) <= 120),  -- card line, e.g. "10% off with student ID"
  quote          text check (char_length(quote) <= 200),          -- exact source text the deal was read from; null for curated
  schedule       jsonb,                -- spec §2; set only when timing = 'scheduled'
  timing         text not null check (timing in ('any_time', 'scheduled', 'unconfirmed')),
  check ((timing = 'scheduled') = (schedule is not null)),
  check (kind = 'student' or timing <> 'any_time'),
  source         text not null check (source in ('curated', 'osm', 'website')),
  source_url     text,                 -- page the deal came from; required for curated and website
  checked_at     timestamptz not null, -- when we last saw the deal at its source
  hidden         boolean not null default false,  -- team removes a bad row without deleting it
  created_at     timestamptz not null default now(),
  check (source = 'osm' or source_url is not null)
);
create index place_deals_restaurant_idx on public.place_deals (restaurant_id) where not hidden;

-- When enrich:deals last scanned this place's website; null means never.
alter table public.restaurants add column deals_checked_at timestamptz;

-- Plain coordinates for the pipeline. Existing columns keep their order; the new ones are appended.
create or replace view public.restaurant_points
with (security_invoker = true) as
select id, place_id, name,
       extensions.st_y(location::extensions.geometry) as lat,
       extensions.st_x(location::extensions.geometry) as lng,
       website, address, osm_tags, media_checked_at,
       deals_checked_at, last_seen_at
from public.restaurants;

-- Access.
alter table public.place_deals enable row level security;

create policy "deals: read visible" on public.place_deals
  for select to anon, authenticated using (not hidden);

revoke all on public.place_deals from anon, authenticated;
grant select on public.place_deals to anon, authenticated;

revoke all on public.restaurant_points from anon, authenticated;
grant select on public.restaurant_points to service_role;
