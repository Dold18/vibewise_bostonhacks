-- User accounts: per-user settings and a private vibe history (DECISIONS.md P-012).
-- Spec: docs/superpowers/specs/2026-11-21-user-accounts-vibe-theme-design.md
-- No location of any kind is stored here.

-- Scores use the vibe vocabulary v1 (DATA_MODEL.md §3): a non-empty object of
-- known keys, each a JSON number in [0, 1]. The client validates first; this is the backstop.
create or replace function public.is_valid_vibe_scores(s jsonb)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select jsonb_typeof(s) = 'object'
     and s <> '{}'::jsonb
     and not exists (
       select 1
       from jsonb_each(s) as e(key, value)
       where e.key not in ('cozy', 'lively', 'upscale', 'divey', 'aesthetic',
                           'quiet', 'date_night', 'group_friendly', 'late_night', 'outdoor')
          -- CASE, not OR: Postgres may evaluate OR operands in any order, and
          -- casting a non-number to numeric would raise instead of failing the check.
          or case when jsonb_typeof(e.value) = 'number'
                  then (e.value::text)::numeric not between 0 and 1
                  else true
             end
     );
$$;

create table public.profiles (
  id              uuid primary key references auth.users (id) on delete cascade,
  effects_enabled boolean not null default true,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create table public.vibe_events (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at    timestamptz not null default now(),
  source        text not null check (source in ('quiz', 'text', 'image', 'song', 'place', 'dev')),
  scores        jsonb not null check (public.is_valid_vibe_scores(scores)),
  vocab_version smallint not null default 1,
  place_id      text
);
create index vibe_events_user_time_idx on public.vibe_events (user_id, created_at desc);

-- Every new auth user gets a profile row. The client also upserts its own row
-- on sign-in, which covers anyone who signed up before this trigger existed.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id) values (new.id) on conflict do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

insert into public.profiles (id) select id from auth.users on conflict do nothing;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger profiles_touch_updated_at
  before update on public.profiles
  for each row execute function public.touch_updated_at();

-- Owner-only access. Nobody can edit history; it can only be added to or cleared.
alter table public.profiles enable row level security;
alter table public.vibe_events enable row level security;

create policy "own profile: read" on public.profiles
  for select to authenticated using (id = (select auth.uid()));
create policy "own profile: create" on public.profiles
  for insert to authenticated with check (id = (select auth.uid()));
create policy "own profile: update" on public.profiles
  for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));

create policy "own vibes: read" on public.vibe_events
  for select to authenticated using (user_id = (select auth.uid()));
create policy "own vibes: add" on public.vibe_events
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy "own vibes: clear" on public.vibe_events
  for delete to authenticated using (user_id = (select auth.uid()));

revoke all on public.profiles, public.vibe_events from anon;
grant select, insert, update on public.profiles to authenticated;
grant select, insert, delete on public.vibe_events to authenticated;
revoke update on public.vibe_events from authenticated;
