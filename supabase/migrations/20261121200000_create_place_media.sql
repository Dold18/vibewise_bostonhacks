-- Place photos, collected vibe inputs and student reviews (DECISIONS.md P-013).
-- Spec: docs/superpowers/specs/2026-11-21-place-photos-vibe-sources-design.md §7
-- Pipeline rows are written with the secret key; signed-in users only add and remove their own.

-- In-app reviews: our own data (DATA_MODEL.md §4), plus `hidden` for removal by the team.
create table public.student_reviews (
  id             bigint generated by default as identity primary key,
  restaurant_id  bigint not null references public.restaurants (id) on delete cascade,
  author_id      uuid default auth.uid() references auth.users (id) on delete cascade, -- null for seeded demo reviews
  rating         smallint check (rating between 1 and 5),
  body           text not null,
  vibe_tags      text[] not null default '{}',     -- DATA_MODEL.md §3 keys
  is_seed        boolean not null default false,   -- team-written demo content; labeled in the UI
  hidden         boolean not null default false,
  created_at     timestamptz not null default now()
);
create index student_reviews_restaurant_idx on public.student_reviews (restaurant_id);

create table public.place_photos (
  id              bigint generated by default as identity primary key,
  restaurant_id   bigint not null references public.restaurants (id) on delete cascade,
  kind            text not null check (kind in ('student', 'licensed', 'website')),
  source          text not null check (source in ('upload', 'osm', 'wikidata', 'commons', 'mapillary', 'website')),
  match_method    text not null check (match_method in ('upload', 'osm_tag', 'wikidata', 'name_match', 'nearest_facing', 'website')),
  url             text,                -- display URL; null for mapillary and uploads
  storage_path    text,                -- uploads only (bucket place-photos)
  mapillary_id    text,                -- mapillary only; its thumbnail URLs expire
  page_url        text,                -- link-back: Commons file page, website page, Mapillary image page
  license         text,                -- e.g. 'CC BY-SA 4.0'; null for website photos and uploads
  credit          text,                -- author or domain, as displayed
  author_id       uuid default auth.uid() references auth.users (id) on delete cascade,  -- uploads only
  review_id       bigint references public.student_reviews (id) on delete cascade,
  rank            smallint not null check (rank between 1 and 5),     -- display rank by source (spec §4.1)
  is_seed         boolean not null default false,
  hidden          boolean not null default false,
  created_at      timestamptz not null default now(),
  checked_at      timestamptz,
  check (source in ('mapillary', 'upload') or url is not null),
  check (source <> 'mapillary' or mapillary_id is not null),
  check (source <> 'upload' or storage_path is not null)
);
create index place_photos_restaurant_idx on public.place_photos (restaurant_id, rank);
create unique index place_photos_restaurant_url_idx on public.place_photos (restaurant_id, url) where url is not null;
create unique index place_photos_restaurant_mapillary_idx on public.place_photos (restaurant_id, mapillary_id) where mapillary_id is not null;

-- Text the later vibe step reads. Holds crawled website text, so it is never public (brief §11).
create table public.place_vibe_inputs (
  restaurant_id   bigint not null references public.restaurants (id) on delete cascade,
  source          text not null check (source in ('website', 'wiki', 'osm_tags', 'city_licenses', 'student_reviews')),
  content         text not null,
  source_url      text,
  fetched_at      timestamptz not null default now(),
  primary key (restaurant_id, source)
);

-- When enrich:media last processed a place; null means never.
alter table public.restaurants add column media_checked_at timestamptz;

-- Plain coordinates for the pipeline (PostgREST returns geography as hex EWKB). Pipeline only.
create view public.restaurant_points
with (security_invoker = true) as
select id, place_id, name,
       extensions.st_y(location::extensions.geometry) as lat,
       extensions.st_x(location::extensions.geometry) as lng,
       website, address, osm_tags, media_checked_at
from public.restaurants;

-- Access.
alter table public.student_reviews enable row level security;
alter table public.place_photos enable row level security;
alter table public.place_vibe_inputs enable row level security;

create policy "reviews: read visible" on public.student_reviews
  for select to anon, authenticated using (not hidden);
create policy "reviews: add own" on public.student_reviews
  for insert to authenticated with check (author_id = (select auth.uid()) and not is_seed and not hidden);
create policy "reviews: delete own" on public.student_reviews
  for delete to authenticated using (author_id = (select auth.uid()));

create policy "photos: read visible" on public.place_photos
  for select to anon, authenticated using (not hidden);
create policy "photos: add own upload" on public.place_photos
  for insert to authenticated
  with check (author_id = (select auth.uid()) and kind = 'student' and source = 'upload'
              and match_method = 'upload' and rank = 1 and not is_seed and not hidden
              -- An upload is a file in the user's own folder: no external URL, license or link-back.
              and url is null and mapillary_id is null and license is null and page_url is null
              and storage_path like (select auth.uid())::text || '/%'
              and (review_id is null or exists (
                select 1 from public.student_reviews r where r.id = review_id and r.author_id = (select auth.uid()))));
create policy "photos: delete own upload" on public.place_photos
  for delete to authenticated using (author_id = (select auth.uid()) and kind = 'student');

revoke all on public.student_reviews, public.place_photos, public.place_vibe_inputs from anon, authenticated;
grant select on public.student_reviews, public.place_photos to anon, authenticated;
grant delete on public.student_reviews, public.place_photos to authenticated;
-- Column-level insert: author_id comes from its auth.uid() default; ids, flags and credits can't be supplied.
grant insert (restaurant_id, rating, body, vibe_tags) on public.student_reviews to authenticated;
grant insert (restaurant_id, kind, source, match_method, storage_path, review_id, rank) on public.place_photos to authenticated;

revoke all on public.restaurant_points from anon, authenticated;
grant select on public.restaurant_points to service_role;

-- Student photo uploads: public read, each user writes only under their own folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('place-photos', 'place-photos', true, 5242880, '{image/jpeg,image/png,image/webp}')
on conflict (id) do nothing;

create policy "place-photos: upload own" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'place-photos' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "place-photos: delete own" on storage.objects
  for delete to authenticated
  using (bucket_id = 'place-photos' and (storage.foldername(name))[1] = (select auth.uid())::text);
