create extension if not exists postgis with schema extensions;
create extension if not exists vector with schema extensions;

create table restaurants (
  id                        bigint generated by default as identity primary key,
  -- Canonical string ID used on the wire (CONTRACTS.md Place.id), e.g. 'osm:node/123456'.
  place_id                  text not null unique,
  source                    text not null check (source in ('osm', 'foursquare')),
  source_id                 text not null,
  fsq_place_id              text unique,
  name                      text not null,
  location                  extensions.geography(Point, 4326) not null,
  address                   text,
  website                   text,
  phone                     text,
  category                  text,             -- maps to CONTRACTS.md PlaceCategory
  -- source_cuisines is written by ingest, menu_cuisines by the menu step; filters read cuisines.
  source_cuisines           text[] not null default '{}',
  menu_cuisines             text[] not null default '{}',
  cuisines                  text[] generated always as (source_cuisines || menu_cuisines) stored,

  -- Hours: null means unknown, never "closed".
  hours                     jsonb,            -- normalized weekly intervals, America/New_York local time
  hours_raw                 text,             -- OSM opening_hours string as received

  -- Price (CONTRACTS.md: money in USD cents; the brief's numeric dollars column is replaced).
  median_entree_price_cents integer check (median_entree_price_cents > 0),
  price_band                text not null default 'unknown'
                              check (price_band in ('$', '$$', '$$$', '$$$$', 'unknown')),
  price_source              text check (price_source in ('menu', 'estimate')),

  -- Menu profile (PROJECT_BRIEF §5.1, unchanged).
  profile                   jsonb,
  description               text,
  embedding                 extensions.vector(384),      -- the single chosen text model (brief §4)

  -- Ambience / vibe layer (P-010, P-011).
  ambience_description      text,             -- one or two sentences about the room, crowd, mood
  ambience_embedding        extensions.vector(384),      -- SAME text model as `embedding`
  ambience_clip_embedding   extensions.vector(512),      -- CLIP text encoder; dimension follows the pinned CLIP model
  vibe_scores               jsonb,            -- {"cozy": 0.8, ...}; keys from section 3, values in [0,1]
  vibe_vocab_version        smallint,
  vibe_confidence           text check (vibe_confidence in ('high', 'medium', 'low')),
  vibe_sources              text[] not null default '{}',  -- e.g. {website,photos,osm_tags,neighborhood}
  osm_tags                  jsonb,            -- kept vibe-relevant tags: outdoor_seating, internet_access, ...
  context_features          jsonb,            -- computed: neighborhood, bars_within_300m, near_park, near_water, ...

  -- Third-party references: IDs only (P-008). No Yelp/Google content is stored.
  yelp_business_id          text,

  fts tsvector generated always as (
    to_tsvector('english',
      coalesce(name, '') || ' ' || coalesce(description, '') || ' ' || coalesce(ambience_description, ''))
  ) stored,

  last_scraped_at           timestamptz,
  last_seen_at              timestamptz,
  attribution               text not null,    -- e.g. '© OpenStreetMap contributors (ODbL)'
  unique (source, source_id)
);

create index restaurants_location_idx on restaurants using gist (location);
create index restaurants_fts_idx      on restaurants using gin (fts);
create index restaurants_cuisines_idx on restaurants using gin (cuisines);
create index restaurants_price_idx    on restaurants (price_band);
-- No HNSW/IVF vector indexes for the MVP (brief §6.5): exact scans after filtering.

alter table restaurants enable row level security;
create policy "restaurants are readable by everyone" on restaurants
  for select to anon, authenticated using (true);
